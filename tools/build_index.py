#!/usr/bin/env python3
"""Generate INDEX.md from iocs/*/case.yml.   usage: build_index.py [--check]
--check exits 1 if INDEX.md is not up to date (used by CI). Needs PyYAML."""
import glob, os, sys
import yaml

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def link(url, text=None):
    return f'[{text or url}]({url})' if url else ''


def build():
    rows = []
    for p in sorted(glob.glob(os.path.join(ROOT, 'iocs', '*', 'case.yml'))):
        c = yaml.safe_load(open(p, encoding='utf-8'))
        slug = os.path.basename(os.path.dirname(p))
        rules = ', '.join(f'[`{r}`]({r})' for r in c.get('rules') or [])
        vids = [c['video']] if c.get('video') else list(c.get('related_videos') or [])
        video = ', '.join(link(v) for v in vids)
        has_iocs = os.path.exists(os.path.join(os.path.dirname(p), 'iocs.json'))
        iocs = f'[`iocs/{slug}/`](iocs/{slug}/)'
        rows.append(f"| {c['title']} | {c['date']} | {', '.join(c.get('families') or [])} | {rules or 'none'} | {iocs if has_iocs else '[case notes](iocs/%s/)' % slug} | {video or '-'} | {link(c.get('gist'), 'gist') or '-'} |")
    head = ('# Case index\n\nGenerated by `tools/build_index.py` from `iocs/*/case.yml`. Do not edit by hand.\n\n'
            '| Case | Date | Families | Rules | IOCs | Video | Gist |\n|---|---|---|---|---|---|---|\n')
    return head + '\n'.join(rows) + '\n'


if __name__ == '__main__':
    out = build()
    path = os.path.join(ROOT, 'INDEX.md')
    if '--check' in sys.argv:
        cur = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        if cur != out:
            print('INDEX.md is stale: run tools/build_index.py')
            sys.exit(1)
        print('INDEX.md up to date')
    else:
        open(path, 'w', encoding='utf-8').write(out)
        print('wrote INDEX.md')
